#ifndef PS2_REGS_H
#define PS2_REGS_H

#include <stdint.h>

/* Keep these hand-written definitions aligned with rtl/ps2_define.svh. */
#define PS2_CTRL_OFFSET              UINT32_C(0x000)
#define PS2_STATUS_OFFSET            UINT32_C(0x004)
#define PS2_RXDATA_OFFSET            UINT32_C(0x008)
#define PS2_TXDATA_OFFSET            UINT32_C(0x00C)
#define PS2_FIFO_STATUS_OFFSET       UINT32_C(0x010)
#define PS2_FIFO_CTRL_OFFSET         UINT32_C(0x014)
#define PS2_RX_WATERMARK_OFFSET      UINT32_C(0x018)
#define PS2_TX_WATERMARK_OFFSET      UINT32_C(0x01C)
#define PS2_FILTER_OFFSET            UINT32_C(0x020)
#define PS2_INHIBIT_CYCLES_OFFSET    UINT32_C(0x024)
#define PS2_FRAME_TIMEOUT_OFFSET     UINT32_C(0x028)
#define PS2_COMMAND_OFFSET           UINT32_C(0x02C)
#define PS2_ERROR_STATUS_OFFSET      UINT32_C(0x030)
#define PS2_INTR_STATE_OFFSET        UINT32_C(0x034)
#define PS2_INTR_ENABLE_OFFSET       UINT32_C(0x038)
#define PS2_INTR_TEST_OFFSET         UINT32_C(0x03C)
#define PS2_IP_ID_OFFSET             UINT32_C(0x0F4)
#define PS2_IP_VERSION_OFFSET        UINT32_C(0x0F8)
#define PS2_CAPABILITY_OFFSET        UINT32_C(0x0FC)

#define PS2_CTRL_ENABLE_MASK         UINT32_C(0x00000001)
#define PS2_STATUS_RX_ACTIVE_MASK    UINT32_C(0x00000004)
#define PS2_STATUS_TX_ACTIVE_MASK    UINT32_C(0x00000008)
#define PS2_STATUS_RX_EMPTY_MASK     UINT32_C(0x00000010)
#define PS2_STATUS_RX_FULL_MASK      UINT32_C(0x00000020)
#define PS2_STATUS_TX_EMPTY_MASK     UINT32_C(0x00000040)
#define PS2_STATUS_TX_FULL_MASK      UINT32_C(0x00000080)
#define PS2_STATUS_CONFIG_VALID_MASK UINT32_C(0x00001000)

#define PS2_RXDATA_DATA_MASK         UINT32_C(0x000000FF)
#define PS2_RXDATA_ERROR_SHIFT       8U
#define PS2_RXDATA_ERROR_MASK        UINT32_C(0x00000700)
#define PS2_RXDATA_VALID_MASK        UINT32_C(0x00008000)
#define PS2_RXDATA_LEVEL_SHIFT       16U
#define PS2_RXDATA_LEVEL_MASK        UINT32_C(0x00FF0000)

#define PS2_FIFO_CTRL_RX_FLUSH_MASK  UINT32_C(0x00000001)
#define PS2_FIFO_CTRL_TX_FLUSH_MASK  UINT32_C(0x00000002)
#define PS2_COMMAND_ABORT_MASK       UINT32_C(0x00000001)
#define PS2_COMMAND_SOFT_RESET_MASK  UINT32_C(0x00000002)

#define PS2_RX_ERROR_START_MASK      UINT32_C(0x00000001)
#define PS2_RX_ERROR_PARITY_MASK     UINT32_C(0x00000002)
#define PS2_RX_ERROR_STOP_MASK       UINT32_C(0x00000004)
#define PS2_RX_ERROR_TIMEOUT_MASK    UINT32_C(0x00000008)
#define PS2_RX_ERROR_OVERFLOW_MASK   UINT32_C(0x00000010)
#define PS2_TX_ERROR_TIMEOUT_MASK    UINT32_C(0x00000020)
#define PS2_TX_ERROR_NO_ACK_MASK     UINT32_C(0x00000040)
#define PS2_TX_ERROR_ABORTED_MASK    UINT32_C(0x00000080)
#define PS2_BUS_ERROR_STUCK_MASK     UINT32_C(0x00000100)
#define PS2_ERROR_VALID_MASK         UINT32_C(0x000001FF)

#define PS2_INTR_RX_WATERMARK_MASK   UINT32_C(0x00000001)
#define PS2_INTR_TX_WATERMARK_MASK   UINT32_C(0x00000002)
#define PS2_INTR_TX_DONE_MASK        UINT32_C(0x00000004)
#define PS2_INTR_RX_ERROR_MASK       UINT32_C(0x00000008)
#define PS2_INTR_TX_ERROR_MASK       UINT32_C(0x00000010)
#define PS2_INTR_BUS_ERROR_MASK      UINT32_C(0x00000020)
#define PS2_INTR_VALID_MASK          UINT32_C(0x0000003F)

#define PS2_IP_ID_VALUE              UINT32_C(0x50533232)
#define PS2_IP_VERSION_VALUE         UINT32_C(0x00020000)
#define PS2_CAPABILITY_FEATURES      UINT32_C(0x3F)
#define PS2_ABI_VERSION              UINT32_C(0x02)

#endif
